package com.zoomify.camera

import android.content.ContentValues
import android.content.Context
import android.provider.MediaStore

/** A 3D LUT: [size]^3 RGB entries, red changing fastest (the .cube order). */
class Lut(val id: String, val title: String, val size: Int, val data: FloatArray) {
    /** Trilinear lookup, for the CPU photo path. [rgb] in 0..1, written in place. */
    fun apply(rgb: FloatArray) {
        val n = size - 1
        val r = rgb[0].coerceIn(0f, 1f) * n
        val g = rgb[1].coerceIn(0f, 1f) * n
        val b = rgb[2].coerceIn(0f, 1f) * n
        val r0 = r.toInt().coerceAtMost(n - 1); val g0 = g.toInt().coerceAtMost(n - 1); val b0 = b.toInt().coerceAtMost(n - 1)
        val fr = r - r0; val fg = g - g0; val fb = b - b0
        for (c in 0..2) {
            fun at(ri: Int, gi: Int, bi: Int) = data[((bi * size + gi) * size + ri) * 3 + c]
            val c00 = at(r0, g0, b0) + (at(r0 + 1, g0, b0) - at(r0, g0, b0)) * fr
            val c10 = at(r0, g0 + 1, b0) + (at(r0 + 1, g0 + 1, b0) - at(r0, g0 + 1, b0)) * fr
            val c01 = at(r0, g0, b0 + 1) + (at(r0 + 1, g0, b0 + 1) - at(r0, g0, b0 + 1)) * fr
            val c11 = at(r0, g0 + 1, b0 + 1) + (at(r0 + 1, g0 + 1, b0 + 1) - at(r0, g0 + 1, b0 + 1)) * fr
            val c0 = c00 + (c10 - c00) * fg
            val c1 = c01 + (c11 - c01) * fg
            rgb[c] = c0 + (c1 - c0) * fb
        }
    }
}

/** Built-in .cube LUTs shipped in assets/luts (generated by tools/generate_luts.py). */
object LutLibrary {
    const val LOG_LUT_ID = "zoomify_log_to_rec709"

    /** Creative looks, in menu order. */
    val creativeIds = listOf("teal_orange", "warm_film", "cool_matte", "mono_classic", "bleach_bypass", "golden_hour")

    private val cache = HashMap<String, Lut>()

    @Synchronized
    fun load(context: Context, id: String): Lut? = cache[id] ?: try {
        parse(id, context.assets.open("luts/$id.cube").bufferedReader().readText()).also { cache[id] = it }
    } catch (e: Exception) {
        null
    }

    fun parse(id: String, text: String): Lut {
        var title = id
        var size = 0
        val values = ArrayList<Float>()
        for (raw in text.lineSequence()) {
            val line = raw.trim()
            if (line.isEmpty() || line.startsWith("#")) continue
            when {
                line.startsWith("TITLE") -> title = line.substringAfter("TITLE").trim().trim('"')
                line.startsWith("LUT_3D_SIZE") -> size = line.substringAfter("LUT_3D_SIZE").trim().toInt()
                line.startsWith("DOMAIN_") || line.startsWith("LUT_1D") -> Unit
                line[0].isDigit() || line[0] == '-' || line[0] == '.' -> {
                    val parts = line.split(Regex("\\s+"))
                    if (parts.size >= 3) {
                        values += parts[0].toFloat(); values += parts[1].toFloat(); values += parts[2].toFloat()
                    }
                }
            }
        }
        require(size >= 2 && values.size == size * size * size * 3) { "Bad LUT $id" }
        return Lut(id, title, size, values.toFloatArray())
    }

    /** Saves a LUT's .cube to Downloads/Zoomify, e.g. the Log LUT for grading in Resolve or Premiere. */
    fun exportToDownloads(context: Context, id: String): Boolean = try {
        val bytes = context.assets.open("luts/$id.cube").readBytes()
        val values = ContentValues().apply {
            put(MediaStore.MediaColumns.DISPLAY_NAME, "$id.cube")
            put(MediaStore.MediaColumns.MIME_TYPE, "application/octet-stream")
            put(MediaStore.MediaColumns.RELATIVE_PATH, "Download/Zoomify")
        }
        val uri = context.contentResolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, values)
        uri != null && context.contentResolver.openOutputStream(uri)?.use { it.write(bytes); true } == true
    } catch (e: Exception) {
        false
    }
}
